"""
Build the MicroBlaze V co-processor firmware and turn it into a C array for
the A53 board test (which loads it into the co-processor's memory).

    python sw/mbv/build.py

Output: sw/mbv/build/mbv_fw.elf, .bin, .lst, and sw/board_test/mbv_fw.h.
Uses the RISC-V GCC shipped with Vitis (riscv64-unknown-elf-gcc, which is
AMD's riscv32 toolchain); set RISCV_GCC to use another one.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(HERE, "build")
OUT_H = os.path.normpath(os.path.join(HERE, "..", "board_test", "mbv_fw.h"))

GCC = os.environ.get("RISCV_GCC") or next(
    (p for p in (r"C:\AMDDesignTools\2026.1\Vitis\gnu\riscv\nt\bin\riscv64-unknown-elf-gcc.exe",
                 r"C:\AMDDesignTools\2026.1\gnu\riscv\nt\bin\riscv64-unknown-elf-gcc.exe",
                 "/tools/Xilinx/2026.1/Vitis/gnu/riscv/lin/bin/riscv64-unknown-elf-gcc")
     if os.path.exists(p)), "riscv64-unknown-elf-gcc")
TOOL = GCC[: -len("gcc.exe")] if GCC.endswith(".exe") else GCC[: -len("gcc")]
EXE = ".exe" if GCC.endswith(".exe") else ""

CFLAGS = ["-march=rv32imc_zicsr", "-mabi=ilp32", "-O2", "-g", "-Wall", "-Wextra",
          "-ffreestanding", "-nostdlib", "-nostartfiles", "-fno-builtin",
          "-Wl,--build-id=none", "-Wl,--no-warn-rwx-segments"]


def run(cmd):
    print(" ".join(cmd))
    subprocess.run(cmd, check=True)


def main():
    os.makedirs(BUILD, exist_ok=True)
    elf = os.path.join(BUILD, "mbv_fw.elf")
    binf = os.path.join(BUILD, "mbv_fw.bin")
    run([GCC, *CFLAGS, "-T", os.path.join(HERE, "mbv.ld"),
         os.path.join(HERE, "crt0.S"), os.path.join(HERE, "main.c"),
         "-lgcc", "-o", elf])
    run([TOOL + "objcopy" + EXE, "-O", "binary", elf, binf])
    with open(os.path.join(BUILD, "mbv_fw.lst"), "w") as lst:
        subprocess.run([TOOL + "objdump" + EXE, "-d", "-S", elf], check=True, stdout=lst)

    data = open(binf, "rb").read()
    data += b"\0" * (-len(data) % 4)
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    with open(OUT_H, "w", newline="\n") as h:
        h.write("/* Generated by sw/mbv/build.py from sw/mbv/ - do not edit. */\n")
        h.write("#ifndef MBV_FW_H\n#define MBV_FW_H\n\n")
        h.write("#define MBV_FW_WORDS %d\n" % len(words))
        h.write("static const unsigned int mbv_fw[MBV_FW_WORDS] = {\n")
        for i in range(0, len(words), 6):
            h.write("    " + ", ".join("0x%08x" % w for w in words[i:i + 6]) + ",\n")
        h.write("};\n\n#endif\n")
    print("%d bytes -> %s" % (len(data), OUT_H))


if __name__ == "__main__":
    sys.exit(main())
