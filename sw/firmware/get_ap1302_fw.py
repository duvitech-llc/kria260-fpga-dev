"""
Fetch the AP1302 ISP firmware for the KV260 (cam=isp) and turn it into a C
header for the A53 board test.

    python -I sw/firmware/get_ap1302_fw.py

The firmware is AMD's, shipped in the Ubuntu source package
linux-firmware-xilinx-ap1302 (version 2.0, "essential for ap1302 to work on
rev 2.0 kv260 boards"). It is not ours to redistribute: the tarball, the .bin
and the generated sw/board_test/ap1302_fw.h are all git-ignored. Run this
script on each machine that builds the ISP test.

Output:
    sw/firmware/linux-firmware-xilinx-ap1302_2.0.orig.tar.gz   (download)
    sw/firmware/ap1302_ar1335_single_fw.bin                    (extracted)
    sw/board_test/ap1302_fw.h                                  (C array)
"""
import hashlib
import os
import sys
import tarfile
import urllib.request

URL = ("https://launchpad.net/ubuntu/+archive/primary/+sourcefiles/"
       "linux-firmware-xilinx-ap1302/1:2.0-0ubuntu2/"
       "linux-firmware-xilinx-ap1302_2.0.orig.tar.gz")
NAME = "ap1302_ar1335_single_fw.bin"

HERE = os.path.dirname(os.path.abspath(__file__))
TARBALL = os.path.join(HERE, os.path.basename(URL))
BIN = os.path.join(HERE, NAME)
HEADER = os.path.normpath(os.path.join(HERE, "..", "board_test", "ap1302_fw.h"))


def main():
    if not os.path.exists(TARBALL):
        print("downloading", URL)
        with urllib.request.urlopen(URL, timeout=60) as r, open(TARBALL, "wb") as f:
            f.write(r.read())
    print("tarball sha256", hashlib.sha256(open(TARBALL, "rb").read()).hexdigest())

    with tarfile.open(TARBALL, "r:gz") as t:
        members = [m for m in t.getmembers() if m.isfile()]
        for m in members:
            print("  %8d  %s" % (m.size, m.name))
        pick = [m for m in members if os.path.basename(m.name) == NAME]
        if not pick:
            sys.exit("%s is not in the tarball (see the list above)" % NAME)
        data = t.extractfile(pick[0]).read()      # read only; nothing is extracted to disk by path
    with open(BIN, "wb") as f:
        f.write(data)

    pll_size = int.from_bytes(data[0:2], "little")
    crc = int.from_bytes(data[2:4], "little")
    print("%s: %d bytes, header: PLL init %d bytes, CRC 0x%04x" % (NAME, len(data), pll_size, crc))
    if pll_size > len(data) - 4:
        sys.exit("unexpected header: PLL init size larger than the file")

    with open(HEADER, "w", newline="\n") as h:
        h.write("/* Generated by sw/firmware/get_ap1302_fw.py from %s - AMD firmware,\n" % NAME)
        h.write(" * not for redistribution; git-ignored. */\n")
        h.write("#ifndef AP1302_FW_H\n#define AP1302_FW_H\n\n")
        h.write("#define AP1302_FW_SIZE %d\n" % len(data))
        h.write("static const unsigned char ap1302_fw[AP1302_FW_SIZE] = {\n")
        for i in range(0, len(data), 16):
            h.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
        h.write("};\n\n#endif\n")
    print("wrote", HEADER)


if __name__ == "__main__":
    main()
